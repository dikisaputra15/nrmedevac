            <h6 class="fw-bold">Overview</h6>
            <p class="text-justify">Primary and preventive care is delivered through the Naoero Public Health Centre in Denig District, run by the Department of Health and Medical Services. It provides public-health programs such as immunization, maternal and child health and non-communicable disease prevention, and it runs community and school outreach and a mobile public-health service. The NMC also lists a Community Health service among its departments.</p>
            <p class="text-justify"><strong>Note:</strong> The 2025 Act does not name the Naoero Public Health Centre in its Schedule. However, the Minister may declare any hospital, health center or clinic a health and medical service facility by Gazette notice (Section 5(2)(b)), and as a government-funded facility it falls within the Section 4 definition. We did not find the relevant Gazette notice. Record it as &ldquo;Public Health Center &mdash; public (Department of Health and Medical Services).&rdquo; Government plans list a redevelopment of the Naoero Public Health Centre.</p>
            <h6 class="fw-bold">Role</h6>
            <ul>
                <li>Serve as the main public-health and preventive-care facility, including the national immunization program</li>
                <li>Deliver community and school outreach, including a public-health mobile service</li>
                <li>Refer patients needing diagnosis or treatment to the Naoero Medical Centre.</li>
            </ul>
            <h6 class="fw-bold">Clinical Service</h6>
